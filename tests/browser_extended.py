"""Additional inlined-browser interaction checks. These do not verify real YouTube or Sites deployment."""
from playwright.sync_api import sync_playwright
from browser_smoke import html, MOCK, SRT

def run():
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-web-security'])
  page=browser.new_page(viewport={'width':1280,'height':900});page.set_default_timeout(3500)
  errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  page.evaluate(MOCK);page.set_content(html,wait_until='domcontentloaded')
  page.locator('.first-lesson [data-action="open-add"]').click()
  page.locator('#import-url').fill('https://www.youtube.com/watch?v=dQw4w9WgXcQ')
  page.locator('#import-title').fill('Test lesson')
  page.locator('#transcript-text').fill(SRT)
  page.locator('[data-action="preview-import"]').click();page.locator('[data-action="save-import"]').click()
  if not page.locator('.queue-panel').count():page.locator('.player-top [data-action="queue"]').click()
  page.locator('.phrase-row:first-child [data-action="queue-menu"]').click()
  page.locator('[data-action="edit-phrase"]').click()
  page.locator('#edit-text').fill('Welcome to my interview.')
  page.locator('#edit-end').fill('3.2')
  page.locator('#edit-pause').fill('3')
  page.locator('[data-action="save-edit"]').click()
  assert 'Welcome to my interview.' in page.locator('.phrase-text').inner_text()
  if not page.locator('.queue-panel').count():page.locator('.player-top [data-action="queue"]').click()
  page.locator('.phrase-row:first-child [data-action="queue-menu"]').click()
  page.locator('[data-action="split-phrase"]').click()
  page.locator('#split-index').select_option('2')
  page.locator('#split-time').fill('2.2')
  page.locator('[data-action="apply-split"]').click()
  print('after split modal',page.locator('.modal h2').all_text_contents(),'toast',page.locator('#toast').inner_text(),flush=True)
  if not page.locator('.queue-panel').count():page.locator('.player-top [data-action="queue"]').click()
  assert page.locator('.phrase-row').count()==3
  page.locator('[data-action="undo"]').click()
  if not page.locator('.queue-panel').count():page.locator('.player-top [data-action="queue"]').click()
  assert page.locator('.phrase-row').count()==2
  page.locator('.queue-panel [data-action="queue"]').click()
  page.locator('.player-top [data-action="view"]').click()
  page.locator('.lesson-card [data-action="favourite"]').click()
  page.locator('.lesson-card [data-action="lesson-actions"]').click()
  page.locator('#rename-lesson').fill('Renamed lesson')
  page.locator('[data-action="save-lesson-meta"]').click()
  assert 'Renamed lesson' in page.locator('.lesson-card').inner_text()
  page.locator('.sidebar [data-view="collections"]').click()
  page.locator('[data-action="new-collection"]').click()
  page.locator('#new-collection-name').fill('UK Podcasts')
  page.locator('[data-action="save-collection"]').click()
  assert 'UK Podcasts' in page.locator('.collection-card').inner_text()
  page.locator('.sidebar [data-view="settings"]').click()
  page.locator('[data-pref="theme"]').select_option('light')
  assert 'light' in page.locator('body').get_attribute('class')
  assert not errors, errors
  print('extended PASS: phrase edit, split, undo, lesson rename, favourite, collection, theme and no uncaught errors')
  browser.close()
if __name__=='__main__':run()
